import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LANGUAGES = ('zh-Hant', 'zh-Hans', 'en')


def articles(name):
    text = (ROOT / name).read_text(encoding='utf-8')
    found = dict(re.findall(r'<article lang="([^"]+)"[^>]*>(.*?)</article>', text, re.S))
    return text, found


class LegalPagesTest(unittest.TestCase):
    def test_every_language_has_the_same_sections(self):
        for name in ('privacy.html', 'terms.html'):
            _, found = articles(name)
            self.assertEqual(sorted(found), sorted(LANGUAGES), name)
            counts = {lang: body.count('<h2>') for lang, body in found.items()}
            self.assertEqual(len(set(counts.values())), 1, f'{name}: {counts}')
            self.assertGreater(counts['en'], 5, name)
            # The Simplified article is generated by tools/build_legal.py, never left empty or Traditional.
            self.assertNotIn('隱私權政策' if name == 'privacy.html' else '使用條款', found['zh-Hans'].split('</h2>')[0])

    def test_contact_and_cross_links(self):
        emails = set()
        for name, other in (('privacy.html', 'terms.html'), ('terms.html', 'privacy.html')):
            text, found = articles(name)
            emails.update(re.findall(r'mailto:([^"]+)"', text))
            for body in found.values():
                self.assertIn(f'href="{other}"', body)
                self.assertIn('mailto:', body)
            self.assertIn('src="js/legal.js"', text)
        self.assertEqual(len(emails), 1, emails)

    def test_lobby_links_to_both_pages(self):
        lobby = (ROOT / 'templates/lobby.html').read_text(encoding='utf-8')
        self.assertIn('href="privacy.html"', lobby)
        self.assertIn('href="terms.html"', lobby)


if __name__ == '__main__':
    unittest.main()
